for (const [locale, additions] of Object.entries(TRANSLATIONS)) {
  const path = `messages/${locale}.json`;
  const data = JSON.parse(readFileSync(path, "utf8"));

  // Merge sidebar.help
  if (!data.sidebar) data.sidebar = {};
  Object.assign(data.sidebar, additions.sidebar);

  // Replace the entire help namespace
  data.help = additions.help;

  writeFileSync(path, JSON.stringify(data, null, 2) + "\n");
  console.log(`${locale}: help namespace + sidebar.help merged`);
}
